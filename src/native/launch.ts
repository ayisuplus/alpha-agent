import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

/**
 * Single place that constructs how Alpha launches the native OMP process.
 * RPC and terminal modes share this construction and may differ only in `--mode`.
 */

export interface LaunchOptions {
  /** Repository root: holds node_modules, presets/ and src/native/. */
  appRoot: string;
  /** Working directory for the OMP process (the session's project directory). */
  cwd: string;
  /** Session file directory passed as PI_CODING_AGENT_SESSION_DIR. */
  sessionDir: string;
  /** Alpha's session id, passed to the extensions. */
  sessionId: string;
  /** Alpha data root (.alpha), passed to the extensions. */
  dataRoot: string;
  /** OMP session id to restore explicitly via --resume; omit for a fresh session. */
  ompSessionId?: string;
  mode: "rpc" | "terminal";
  /** Terminal mode only: offer the bundled Alpha theme when the user has no theme set. */
  terminalTheme?: boolean;
  /** Agent dir (getAgentDir) used to install the bundled theme for terminal mode. */
  agentDir?: string;
  /** Overrides the generated browser.cdpUrl (desktop browser host endpoint). */
  browserCdpUrl?: string;
}

export interface LaunchPlan {
  /** Full argv after the executable: cli path first. */
  argv: string[];
  /** Complete environment for the child; an allowlist, never containing credentials. */
  env: Record<string, string>;
  /** The generated per-launch OMP config overlay (written by writeLaunchConfig). */
  configPath: string;
}

/** OS/runtime variables the OMP process and its tools actually need on Windows and POSIX. */
const ENV_ALLOWLIST = [
  "PATH", "Path", "PATHEXT", "SystemRoot", "SYSTEMROOT", "WINDIR", "ComSpec", "COMSPEC",
  "TEMP", "TMP", "TMPDIR", "USERPROFILE", "HOMEDRIVE", "HOMEPATH", "HOME", "APPDATA",
  "LOCALAPPDATA", "ProgramData", "ProgramFiles", "ProgramFiles(x86)", "ProgramW6432",
  "PUBLIC", "USERNAME", "USERDOMAIN", "COMPUTERNAME", "NUMBER_OF_PROCESSORS",
  "PROCESSOR_ARCHITECTURE", "LANG", "LC_ALL", "TZ", "TERM", "COLORTERM",
] as const;

const ALLOWLIST = new Set<string>(ENV_ALLOWLIST);

/** Belt and braces: even if the allowlist grows, credentials and debug ports never pass. */
function denied(key: string): boolean {
  return /(TOKEN|SECRET|PASSWORD|API_?KEY|_KEY$|CDP|DEBUG_PORT|BRIDGE)/i.test(key);
}

export function buildLaunchEnv(options: LaunchOptions, source: NodeJS.ProcessEnv = process.env): Record<string, string> {
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(source)) {
    if (value !== undefined && ALLOWLIST.has(key) && !denied(key)) env[key] = value;
  }
  env.PI_CODING_AGENT_SESSION_DIR = options.sessionDir;
  env.ALPHA_NATIVE_SESSION_ID = options.sessionId;
  env.ALPHA_DATA_ROOT = options.dataRoot;
  if (source.ALPHA_CVM_MODE) env.ALPHA_CVM_MODE = source.ALPHA_CVM_MODE;
  if (source.PI_CODING_AGENT_DIR) env.PI_CODING_AGENT_DIR = source.PI_CODING_AGENT_DIR;
  if (source.ALPHA_COMFY_URL) {
    const url = new URL(source.ALPHA_COMFY_URL);
    if (url.protocol !== "http:" || url.hostname !== "127.0.0.1") throw new Error("ComfyUI must be on loopback");
    env.ALPHA_COMFY_URL = url.origin;
  }
  if (options.mode === "rpc") env.PI_RPC_EMIT_TITLE = "1";
  if (options.mode === "terminal" && options.terminalTheme) env.ALPHA_TERMINAL_THEME = "1";
  return env;
}

/** OMP settings overlay regenerated on every launch; never secrets. */
export async function writeLaunchConfig(options: LaunchOptions): Promise<string> {
  const configPath = join(options.dataRoot, "native", "alpha-settings.yml");
  await mkdir(join(options.dataRoot, "native"), { recursive: true });
  const lines = ["# Generated by Alpha on every launch; do not edit while Alpha is running."];
  const cdpUrl = options.browserCdpUrl ?? process.env.ALPHA_BROWSER_CDP_URL;
  if (cdpUrl && /^http:\/\/127\.0\.0\.1:\d+(\/.*)?$/.test(cdpUrl)) {
    lines.push("browser:", `  cdpUrl: ${cdpUrl}`);
  }
  if (options.mode === "terminal" && options.terminalTheme && options.agentDir) {
    // Bundled "墨·深" theme: installed by name into <agentDir>/themes; never overwrites a user's file.
    const themeSource = join(resolve(options.appRoot), "presets", "terminal-themes", "alpha-ink.json");
    const themesDir = join(options.agentDir, "themes");
    const themeTarget = join(themesDir, "alpha-ink.json");
    const installed = await stat(themeTarget).then(() => true, () => false);
    const bundled = await readFile(themeSource, "utf8").then(text => text, () => null);
    if (!installed && bundled) {
      await mkdir(themesDir, { recursive: true });
      await writeFile(themeTarget, bundled, "utf8");
    }
    if (installed || bundled) lines.push("theme:", "  dark: alpha-ink", "  light: alpha-ink");
  }
  await writeFile(configPath, `${lines.join("\n")}\n`, "utf8");
  return configPath;
}

export async function buildLaunch(options: LaunchOptions): Promise<LaunchPlan> {
  const appRoot = resolve(options.appRoot);
  const cli = join(appRoot, "node_modules", "@oh-my-pi", "pi-coding-agent", "dist", "cli.js");
  const configPath = await writeLaunchConfig(options);
  const argv = [
    cli,
    "--plugin-dir", join(appRoot, "presets", "alpha-plugin"),
    "--append-system-prompt", join(appRoot, "presets", "alpha-identity.md"),
    "--config", configPath,
    "--extension", join(appRoot, "src", "native", "tianshu", "extension.ts"),
    "--extension", join(appRoot, "src", "native", "capabilities", "extension.ts"),
    ...(options.ompSessionId ? ["--resume", options.ompSessionId] : []),
    ...(options.mode === "rpc" ? ["--mode", "rpc-ui"] : []),
  ];
  return { argv, env: buildLaunchEnv(options), configPath };
}

/**
 * Default working directory for new sessions: <workspace root>/workspace.
 * .alpha (session and browser data) stays at <workspace root>/.alpha, never under a default cwd.
 */
export function defaultWorkspaceRoot(workspaceRoot: string): string {
  return resolve(workspaceRoot, "workspace");
}
